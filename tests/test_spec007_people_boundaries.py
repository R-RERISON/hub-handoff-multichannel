def test_supervisor_and_auditor_cannot_mutate_outside_scope(
    tmp_path, monkeypatch,
):
    lab = setup_lab(tmp_path, monkeypatch)
    other_operation(lab)
    app = create_app(database_url=lab.database_url, api_key=KEY)
    with TestClient(app, raise_server_exceptions=False) as client:
        supervisor = auth(client, lab, "supervisor.demo")
        auditor = auth(client, lab, "auditor.demo")
        assert client.patch(
            "/v1/operators/foreign-operator/capacity", headers=supervisor,
            json={"capacity": 1},
        ).status_code == 403
        assert client.patch(
            "/v1/operators/foreign-operator/presence", headers=supervisor,
            json={"presence": "OFFLINE"},
        ).status_code == 403
        assert client.patch(
            "/v1/queues/foreign-queue/members/foreign-operator",
            headers=supervisor, json={"enabled": False},
        ).status_code == 404
        for path, payload in (
            ("/v1/operators/op-ana/capacity", {"capacity": 2}),
            ("/v1/operators/op-ana/presence", {"presence": "AWAY"}),
            ("/v1/queues/n1/members/op-bruno", {"enabled": True}),
        ):
            assert client.patch(
                path, headers=auditor, json=payload,
            ).status_code == 403
    assert operator_state(lab, "foreign-operator") == (3, "AVAILABLE")


def test_valid_scoped_writes_and_operator_self_presence(
    tmp_path, monkeypatch,
):
    lab = setup_lab(tmp_path, monkeypatch)
    app = create_app(database_url=lab.database_url, api_key=KEY)
    with TestClient(app, raise_server_exceptions=False) as client:
        admin = auth(client, lab, "admin.demo")
        supervisor = auth(client, lab, "supervisor.demo")
        ana = auth(client, lab, "ana.demo")
        assert client.patch(
            "/v1/operators/op-ana/capacity", headers=admin,
            json={"capacity": 2},
        ).status_code == 200
        assert client.patch(
            "/v1/operators/op-ana/presence", headers=ana,
            json={"presence": "AWAY"},
        ).status_code == 200
        assert client.patch(
            "/v1/operators/op-bruno/presence", headers=ana,
            json={"presence": "OFFLINE"},
        ).status_code == 403
        assert client.patch(
            "/v1/operators/op-ana/capacity", headers=ana,
            json={"capacity": 4},
        ).status_code == 403
        managed = client.patch(
            "/v1/queues/n1/members/op-bruno", headers=supervisor,
            json={"enabled": True},
        )
        assert managed.status_code == 200, managed.text
        assert operator_state(lab, "op-ana") == (2, "AWAY")
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory() as db:
            assert db.get(QueueMembership, ("n1", "op-bruno")) is not None
    finally:
        engine.dispose()
