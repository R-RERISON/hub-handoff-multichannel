"""SPEC-007/B0 — operation/role boundaries for legacy team mutations.

Every database is generated by lab_environment inside pytest's disposable TEMP.
No original POC database, secrets, or external services.
"""
from __future__ import annotations

from fastapi.testclient import TestClient
from sqlalchemy import select

from handoff_hub.poc_api import create_app
from handoff_hub.poc_db import (
    AuthUser,
    Operation,
    Operator,
    Queue,
    QueueMembership,
    make_session_factory,
)
from scripts import lab_environment
from scripts.release_grant_toggle import bearer


KEY = "spec007-b0-lab-only"


def setup_lab(tmp_path, monkeypatch):
    monkeypatch.setattr(lab_environment.tempfile, "gettempdir", lambda: str(tmp_path))
    return lab_environment.prepare_lab()


def auth(client, lab, username):
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory() as db:
            user = db.scalar(select(AuthUser).where(AuthUser.username == username))
            assert user is not None
            user_id = user.id
    finally:
        engine.dispose()
    return bearer(client, lab.credentials, username, user_id)


def other_operation(lab):
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory.begin() as db:
            db.add(Operation(id="other-op", name="Private remote operation"))
            db.add(Operator(
                id="foreign-operator", operation_id="other-op",
                name="OPERATOR_HIDDEN", capacity=3, presence="AVAILABLE",
            ))
            db.add(Queue(
                id="foreign-queue", operation_id="other-op", name="QUEUE_HIDDEN",
            ))
            db.flush()
            db.add(QueueMembership(
                queue_id="foreign-queue", operator_id="foreign-operator",
            ))
    finally:
        engine.dispose()


def operator_state(lab, operator_id):
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory() as db:
            operator = db.get(Operator, operator_id)
            assert operator is not None
            return (operator.capacity, operator.presence)
    finally:
        engine.dispose()


def test_admin_cannot_write_other_operation_operator_or_membership(
    tmp_path, monkeypatch,
):
    lab = setup_lab(tmp_path, monkeypatch)
    other_operation(lab)
    app = create_app(database_url=lab.database_url, api_key=KEY)
    with TestClient(app, raise_server_exceptions=False) as client:
        admin = auth(client, lab, "admin.demo")
        cases = (
            ("/v1/operators/foreign-operator/capacity", {"capacity": 1}),
            ("/v1/operators/foreign-operator/presence", {"presence": "AWAY"}),
            ("/v1/queues/foreign-queue/members/foreign-operator", {"enabled": False}),
        )
        for path, payload in cases:
            response = client.patch(path, headers=admin, json=payload)
            assert response.status_code == 404
            assert "OPERATOR_HIDDEN" not in response.text
            assert "QUEUE_HIDDEN" not in response.text
        mixed = client.patch(
            "/v1/queues/n1/members/foreign-operator", headers=admin,
            json={"enabled": True},
        )
        assert mixed.status_code == 422
    assert operator_state(lab, "foreign-operator") == (3, "AVAILABLE")
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory() as db:
            assert db.get(
                QueueMembership, ("foreign-queue", "foreign-operator"),
            ) is not None
            assert db.get(QueueMembership, ("n1", "foreign-operator")) is None
    finally:
        engine.dispose()


def test_supervisor_and_auditor_cannot_mutate_outside_scope(
    tmp_path, monkeypatch,
):
    lab = setup_lab(tmp_path, monkeypatch)
    other_operation(lab)
    app = create_app(database_url=lab.database_url, api_key=KEY)
    with TestClient(app, raise_server_exceptions=False) as client:
        supervisor = auth(client, lab, "supervisor.demo")
        auditor = auth(client, lab, "auditor.demo")
        assert client.patch(
            "/v1/operators/foreign-operator/capacity", headers=supervisor,
            json={"capacity": 1},
        ).status_code == 403
        assert client.patch(
            "/v1/operators/foreign-operator/presence", headers=supervisor,
            json={"presence": "OFFLINE"},
        ).status_code == 403
        assert client.patch(
            "/v1/queues/foreign-queue/members/foreign-operator",
            headers=supervisor, json={"enabled": False},
        ).status_code == 404
        for path, payload in (
            ("/v1/operators/op-ana/capacity", {"capacity": 2}),
            ("/v1/operators/op-ana/presence", {"presence": "AWAY"}),
            ("/v1/queues/n1/members/op-bruno", {"enabled": True}),
        ):
            assert client.patch(
                path, headers=auditor, json=payload,
            ).status_code == 403
    assert operator_state(lab, "foreign-operator") == (3, "AVAILABLE")


def test_valid_scoped_writes_and_operator_self_presence(
    tmp_path, monkeypatch,
):
    lab = setup_lab(tmp_path, monkeypatch)
    app = create_app(database_url=lab.database_url, api_key=KEY)
    with TestClient(app, raise_server_exceptions=False) as client:
        admin = auth(client, lab, "admin.demo")
        supervisor = auth(client, lab, "supervisor.demo")
        ana = auth(client, lab, "ana.demo")
        assert client.patch(
            "/v1/operators/op-ana/capacity", headers=admin,
            json={"capacity": 2},
        ).status_code == 200
        assert client.patch(
            "/v1/operators/op-ana/presence", headers=ana,
            json={"presence": "AWAY"},
        ).status_code == 200
        assert client.patch(
            "/v1/operators/op-bruno/presence", headers=ana,
            json={"presence": "OFFLINE"},
        ).status_code == 403
        assert client.patch(
            "/v1/operators/op-ana/capacity", headers=ana,
            json={"capacity": 4},
        ).status_code == 403
        managed = client.patch(
            "/v1/queues/n1/members/op-bruno", headers=supervisor,
            json={"enabled": True},
        )
        assert managed.status_code == 200, managed.text
        assert operator_state(lab, "op-ana") == (2, "AWAY")
    factory, engine = make_session_factory(lab.database_url)
    try:
        with factory() as db:
            assert db.get(QueueMembership, ("n1", "op-bruno")) is not None
    finally:
        engine.dispose()
